-- Android device screening reports.
-- Assign app_metadata.role = "device_reporter" to approved device accounts and
-- app_metadata.role = "admin" to dashboard readers using a trusted admin process.
create table if not exists public.android_device_scan_reports (
  id bigint generated by default as identity primary key,
  installation_id text not null,
  device_label text not null,
  manufacturer text not null,
  model text not null,
  android_version text not null,
  scanned_at timestamptz not null,
  matches jsonb not null default '[]'::jsonb
    check (jsonb_typeof(matches) = 'array'),
  created_by uuid not null default auth.uid() references auth.users(id)
);

create index if not exists android_device_scan_reports_scanned_at_idx
  on public.android_device_scan_reports (scanned_at desc);

alter table public.android_device_scan_reports enable row level security;
revoke all on public.android_device_scan_reports from anon;
grant select, insert on public.android_device_scan_reports to authenticated;
grant usage, select on sequence public.android_device_scan_reports_id_seq to authenticated;

drop policy if exists "Approved device accounts can submit screening reports"
  on public.android_device_scan_reports;
create policy "Approved device accounts can submit screening reports"
  on public.android_device_scan_reports
  for insert to authenticated
  with check (
    created_by = auth.uid()
    and coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') in ('device_reporter', 'admin')
  );

drop policy if exists "Screening admins can read reports"
  on public.android_device_scan_reports;
create policy "Screening admins can read reports"
  on public.android_device_scan_reports
  for select to authenticated
  using (coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') = 'admin');
