-- ── 1. MENTOR PASSKEYS TABLE ─────────────────────────────────
create table if not exists public.mentor_passkeys (
  mentor_name  text primary key,
  passkey_hash text not null,
  updated_at   timestamptz not null default now()
);

alter table public.mentor_passkeys enable row level security;

drop policy if exists "Admins manage mentor passkeys" on public.mentor_passkeys;
create policy "Admins manage mentor passkeys"
  on public.mentor_passkeys
  for all to authenticated
  using (true)
  with check (true);


-- ── 2. PROGRAM DAILY STATUS TABLE ────────────────────────────
create table if not exists public.program_daily_status (
  id             bigint generated by default as identity primary key,
  admission_no   text not null references public.student_profiles(admission_no) on delete cascade,
  mentor_name    text not null,
  program_code   text not null,
  program_name   text not null default '',
  progress_date  date not null,
  completed      boolean not null default false,
  rating         text,
  updated_at     timestamptz not null default now(),
  unique (admission_no, program_code, progress_date)
);

alter table public.program_daily_status enable row level security;

drop policy if exists "Public can read program daily status" on public.program_daily_status;
create policy "Public can read program daily status"
  on public.program_daily_status
  for select to anon, authenticated
  using (true);

drop policy if exists "Admins manage program daily status" on public.program_daily_status;
create policy "Admins manage program daily status"
  on public.program_daily_status
  for all to authenticated
  using (true)
  with check (true);


-- ── 3. RPC: mentor_passkey_valid ─────────────────────────────
create or replace function public.mentor_passkey_valid(
  p_admission_no text,
  p_program_code text,
  p_mentor_name  text,
  p_passkey      text
) returns boolean
  language plpgsql
  security definer
  set search_path = public
as $$
declare
  v_stored_hash    text;
  v_profile_mentor text;
  v_program_mentors text[];
  v_mentor_ok      boolean := false;
begin
  select program_mentors, mentor
  into v_program_mentors, v_profile_mentor
  from student_profiles
  where admission_no = p_admission_no;

  if not found then
    raise exception 'No profile found for admission number %.', p_admission_no;
  end if;

  if v_program_mentors is not null and array_length(v_program_mentors, 1) > 0 then
    select bool_or(lower(trim(m)) = lower(trim(p_mentor_name)))
    into v_mentor_ok
    from unnest(v_program_mentors) as m;
  else
    v_mentor_ok := lower(trim(coalesce(v_profile_mentor, ''))) = lower(trim(p_mentor_name));
  end if;

  if not v_mentor_ok then
    return false;
  end if;

  select passkey_hash
  into v_stored_hash
  from mentor_passkeys
  where lower(trim(mentor_name)) = lower(trim(p_mentor_name));

  if not found then
    raise exception 'Mentor "%" has no passkey set. Ask the Control Room to set one in Supabase.', p_mentor_name;
  end if;

  return trim(v_stored_hash) = trim(p_passkey);
end;
$$;

grant execute on function public.mentor_passkey_valid(text, text, text, text) to anon, authenticated;


-- ── 4. RPC: student_get_program_status ───────────────────────
create or replace function public.student_get_program_status(
  p_admission_no text,
  p_start_date   date,
  p_end_date     date
) returns table (
  progress_date date,
  program_code  text,
  program_name  text,
  completed     boolean,
  rating        text
)
  language sql
  security definer
  set search_path = public
as $$
  select
    pds.progress_date,
    pds.program_code,
    pds.program_name,
    pds.completed,
    pds.rating
  from program_daily_status pds
  where pds.admission_no = p_admission_no
    and pds.progress_date between p_start_date and p_end_date
  order by pds.progress_date, pds.program_code;
$$;

grant execute on function public.student_get_program_status(text, date, date) to anon, authenticated;


-- ── 5. RPC: mentor_get_program_status ────────────────────────
create or replace function public.mentor_get_program_status(
  p_admission_no text,
  p_program_code text,
  p_mentor_name  text,
  p_passkey      text,
  p_start_date   date,
  p_end_date     date
) returns table (
  progress_date date,
  program_code  text,
  program_name  text,
  completed     boolean,
  rating        text
)
  language plpgsql
  security definer
  set search_path = public
as $$
begin
  if not public.mentor_passkey_valid(p_admission_no, p_program_code, p_mentor_name, p_passkey) then
    raise exception 'Incorrect passkey or mentor assignment for this program.';
  end if;

  return query
    select
      pds.progress_date,
      pds.program_code,
      pds.program_name,
      pds.completed,
      pds.rating
    from program_daily_status pds
    where pds.admission_no = p_admission_no
      and pds.program_code = p_program_code
      and pds.progress_date between p_start_date and p_end_date
    order by pds.progress_date;
end;
$$;

grant execute on function public.mentor_get_program_status(text, text, text, text, date, date) to anon, authenticated;


-- ── 6. RPC: mentor_save_program_status ───────────────────────
create or replace function public.mentor_save_program_status(
  p_admission_no  text,
  p_mentor_name   text,
  p_passkey       text,
  p_progress_date date,
  p_program_code  text,
  p_program_name  text,
  p_completed     boolean,
  p_rating        text default null
) returns boolean
  language plpgsql
  security definer
  set search_path = public
as $$
begin
  if not public.mentor_passkey_valid(p_admission_no, p_program_code, p_mentor_name, p_passkey) then
    raise exception 'Incorrect passkey or mentor assignment for this program.';
  end if;

  insert into program_daily_status
    (admission_no, mentor_name, program_code, program_name, progress_date, completed, rating, updated_at)
  values
    (p_admission_no, p_mentor_name, p_program_code, coalesce(p_program_name, ''), p_progress_date, p_completed, p_rating, now())
  on conflict (admission_no, program_code, progress_date)
  do update set
    completed    = excluded.completed,
    rating       = excluded.rating,
    mentor_name  = excluded.mentor_name,
    program_name = excluded.program_name,
    updated_at   = now();

  return true;
end;
$$;

grant execute on function public.mentor_save_program_status(text, text, text, date, text, text, boolean, text) to anon, authenticated;


